def update_language(lang, entries):
    po_path = Path("locale") / lang / "LC_MESSAGES" / "django.po"
    mo_path = Path("locale") / lang / "LC_MESSAGES" / "django.mo"
    po = polib.pofile(str(po_path), encoding="utf-8")

    for msgid, msgstr in entries.items():
        entry = po.find(msgid)
        if entry is None:
            entry = polib.POEntry(msgid=msgid, msgstr=msgstr)
            po.append(entry)
        else:
            entry.msgstr = msgstr
            entry.obsolete = False
            if "fuzzy" in entry.flags:
                entry.flags.remove("fuzzy")

    po.save(str(po_path))
    po.save_as_mofile(str(mo_path))


def main():
    for lang, entries in TRANSLATIONS.items():
        update_language(lang, entries)
        print(f"{lang}: updated {len(entries)} translations")


if __name__ == "__main__":
    main()
